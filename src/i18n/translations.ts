/* Recursively merges `extra` into `target` (objects are merged, everything else is replaced). */
const merge = (target: TranslationTree, extra: TranslationTree): TranslationTree => {
  const out: TranslationTree = { ...target };
  for (const [key, value] of Object.entries(extra)) {
    const current = out[key];
    const bothObjects =
      current && typeof current === "object" && !Array.isArray(current) &&
      typeof value === "object" && !Array.isArray(value);
    out[key] = bothObjects ? merge(current as TranslationTree, value as TranslationTree) : value;
  }
  return out;
};

